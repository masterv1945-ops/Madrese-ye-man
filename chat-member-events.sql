-- ثبت رویدادهای خروج اعضا از گروه، کانال یا گفت‌وگوی مستقیم
-- وابستگی خارجی به chat_rooms ندارد تا سابقهٔ خروج باقی بماند.
CREATE TABLE IF NOT EXISTS public.chat_member_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id text NOT NULL,
  room_kind text NOT NULL DEFAULT 'unknown',
  user_id uuid NOT NULL,
  event_type text NOT NULL CHECK (event_type IN ('left')),
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.chat_member_events ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users can log their own chat leave" ON public.chat_member_events;
CREATE POLICY "Users can log their own chat leave"
ON public.chat_member_events FOR INSERT TO authenticated
WITH CHECK (user_id = auth.uid() AND event_type = 'left');
DROP POLICY IF EXISTS "Users can read their own chat leave events" ON public.chat_member_events;
CREATE POLICY "Users can read their own chat leave events"
ON public.chat_member_events FOR SELECT TO authenticated
USING (user_id = auth.uid());
CREATE INDEX IF NOT EXISTS chat_member_events_user_created_idx
ON public.chat_member_events (user_id, created_at DESC);
