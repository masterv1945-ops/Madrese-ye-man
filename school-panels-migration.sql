-- افزونه پنل مدیر/معلم: برنامه هفتگی و بخش‌نامه هفتگی
-- این فایل را در Supabase > SQL Editor اجرا کنید.
-- این اسکریپت جداول تازه می‌سازد و جداول قبلی نمرات/حضورغیاب را تغییر نمی‌دهد.

create table if not exists public.school_timetable (
  id bigint generated by default as identity primary key,
  grade text not null,
  class_name text not null,
  day_number smallint not null check (day_number between 1 and 6),
  period smallint not null check (period between 1 and 12),
  subject text not null,
  teacher_name text,
  start_time time not null,
  end_time time not null,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  constraint school_timetable_time_order check (end_time > start_time),
  constraint school_timetable_class_period_unique unique (grade, class_name, day_number, period)
);
create index if not exists school_timetable_class_idx
  on public.school_timetable (grade, class_name, day_number, period);

create table if not exists public.school_circulars (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) > 0),
  body text not null check (length(trim(body)) > 0),
  week_start date not null,
  target_scope text not null default 'school' check (target_scope in ('school','grade','class')),
  grade text,
  class_name text,
  is_published boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  published_at timestamptz,
  constraint school_circulars_target_fields check (
    (target_scope = 'school' and grade is null and class_name is null) or
    (target_scope = 'grade' and grade is not null and class_name is null) or
    (target_scope = 'class' and grade is not null and class_name is not null)
  )
);
create index if not exists school_circulars_published_idx
  on public.school_circulars (is_published, week_start desc, created_at desc);
create index if not exists school_circulars_target_idx
  on public.school_circulars (target_scope, grade, class_name);

alter table public.school_timetable enable row level security;
alter table public.school_circulars enable row level security;

drop policy if exists "managers manage school timetable" on public.school_timetable;
create policy "managers manage school timetable"
  on public.school_timetable for all to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'manager'))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'manager'));

drop policy if exists "students parents and assigned teachers read relevant timetable" on public.school_timetable;
create policy "students parents and assigned teachers read relevant timetable"
  on public.school_timetable for select to authenticated
  using (
    exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'manager')
    or exists (select 1 from public.students s where s.user_id = auth.uid() and s.grade = school_timetable.grade and s.class_name = school_timetable.class_name)
    or exists (
      select 1 from public.parent_students ps join public.students s on s.id = ps.student_id
      where ps.parent_id = auth.uid() and s.grade = school_timetable.grade and s.class_name = school_timetable.class_name
    )
    or exists (
      select 1 from public.teachers t join public.teacher_assignments ta on ta.teacher_id = t.id
      where t.user_id = auth.uid() and ta.grade = school_timetable.grade and ta.class_name = school_timetable.class_name
    )
  );

drop policy if exists "managers manage school circulars" on public.school_circulars;
create policy "managers manage school circulars"
  on public.school_circulars for all to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'manager'))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'manager'));

drop policy if exists "school members read relevant published circulars" on public.school_circulars;
create policy "school members read relevant published circulars"
  on public.school_circulars for select to authenticated
  using (
    is_published = true and (
      target_scope = 'school'
      or exists (
        select 1 from public.students s
        where s.user_id = auth.uid() and s.grade = school_circulars.grade
          and (school_circulars.target_scope = 'grade' or s.class_name = school_circulars.class_name)
      )
      or exists (
        select 1 from public.parent_students ps join public.students s on s.id = ps.student_id
        where ps.parent_id = auth.uid() and s.grade = school_circulars.grade
          and (school_circulars.target_scope = 'grade' or s.class_name = school_circulars.class_name)
      )
      or exists (
        select 1 from public.teachers t join public.teacher_assignments ta on ta.teacher_id = t.id
        where t.user_id = auth.uid() and ta.grade = school_circulars.grade
          and (school_circulars.target_scope = 'grade' or ta.class_name = school_circulars.class_name)
      )
    )
  );

